        # Converter a resposta para StreamingResponse no formato OpenAI
        async def convert_to_openai_stream():
            # Verificar se temos o conteúdo no formato esperado
            if isinstance(content_dict, dict):
                # Extrair o conteúdo da mensagem
                message_content = ""
                
                # Tentar extrair o conteúdo de diferentes formatos possíveis
